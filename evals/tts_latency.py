"""Voice reply latency: edge-tts vs ElevenLabs on the same typical replies (ARCHITECTURE.md §10).

    python evals/tts_latency.py [--runs 3]

Needs network; ElevenLabs needs ELEVENLABS_API_KEY (each run uses the characters of every reply). Measures the time
from the request to the complete MP3, which is what the browser waits for before it plays the reply. Writes
evals/results/tts-latency.md.
"""
import argparse
import asyncio
import statistics
import sys
import time
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from linecare import config  # noqa: E402
from linecare.voice.tts import EdgeTTS, ElevenLabsTTS  # noqa: E402

REPLIES = [
    ("en", "short", "Thank you, you are verified. I am checking your line and your router now."),
    ("en", "medium", "Your router has stopped handing out addresses. I can restart it remotely: your internet and TV "
                     "will be off for about three minutes. Shall I go ahead?"),
    ("bg", "short", "Благодаря, потвърдихте самоличността си. Проверявам линията и рутера ви."),
    ("bg", "medium", "Рутерът ви е спрял да раздава адреси. Мога да го рестартирам дистанционно: интернетът и "
                     "телевизията ще спрат за около три минути. Да продължа ли?"),
]
OUT = Path(__file__).resolve().parent / "results" / "tts-latency.md"


async def measure(provider, runs: int) -> dict:
    results = {}
    for language, size, text in REPLIES:
        times, errors = [], []
        for _ in range(runs):
            started = time.perf_counter()
            audio, problem = await provider.synthesize(text, language, config.DEFAULT_VOICE_GENDER)
            if audio:
                times.append(time.perf_counter() - started)
            else:
                errors.append(problem)
        results[(language, size)] = {"times": times, "errors": errors, "chars": len(text)}
    return results


def fmt(times: list[float]) -> str:
    if not times:
        return "–"
    return f"{statistics.median(times):.2f} s (max {max(times):.2f})"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=3)
    args = parser.parse_args()
    providers = {"edge-tts": EdgeTTS()}
    if config.ELEVENLABS_API_KEY:
        providers[f"ElevenLabs ({config.ELEVENLABS_MODEL})"] = ElevenLabsTTS()
    else:
        print("ELEVENLABS_API_KEY not set: measuring edge-tts only")
    measured = {name: asyncio.run(measure(p, args.runs)) for name, p in providers.items()}

    lines = [f"# Voice reply latency ({date.today().isoformat()})", "",
             f"Time from the request to the complete MP3, median and maximum of {args.runs} runs per reply, from "
             "one home internet connection. Generated by `python evals/tts_latency.py`.", "",
             "| Reply | Characters | " + " | ".join(measured) + " |",
             "|---|---|" + "---|" * len(measured)]
    for language, size, text in REPLIES:
        cells = [fmt(m[(language, size)]["times"]) for m in measured.values()]
        lines.append(f"| {language.upper()} {size} | {len(text)} | " + " | ".join(cells) + " |")
    all_times = {name: [t for r in m.values() for t in r["times"]] for name, m in measured.items()}
    lines.append("| **all** | | " + " | ".join(f"**{fmt(t)}**" for t in all_times.values()) + " |")
    errors = [f"- {name}, {lang} {size}: {e}" for name, m in measured.items() for (lang, size), r in m.items()
              for e in r["errors"]]
    if errors:
        lines += ["", "Errors:", *errors]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
